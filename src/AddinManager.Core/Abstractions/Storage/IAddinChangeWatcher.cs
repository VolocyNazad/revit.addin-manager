namespace AddinManager.Core.Abstractions.Storage;

/// <summary>
/// Уведомляет о том, что .addin-файлы на диске могли измениться помимо самого приложения —
/// другой процесс, ручное редактирование в проводнике, вторая копия менеджера. Это дополняет
/// <see cref="IAddinStore"/>/<see cref="IAddinMarkupService"/>, которые отвечают только за то,
/// что приложение читает и пишет само (после собственного <c>Save</c>/<c>SetEnabled</c> вызывающая
/// сторона и так знает, что перечитать — см. <c>ListViewModel</c>, другая сборка, отсюда без
/// <c>cref</c>); этот сервис — единственный источник правды о внешних изменениях.
/// Реализации заменяемы через DI, как и остальные абстракции хранилища.
/// </summary>
public interface IAddinChangeWatcher : IDisposable
{
    /// <summary>
    /// Начинает слежение за диском. Без вызова событие <see cref="Changed"/> никогда не
    /// придёт. Повторный вызов — no-op.
    /// </summary>
    void Start();

    /// <summary>
    /// Диск, возможно, изменился — подписчику стоит перечитать актуальное состояние.
    /// Может сработать в произвольном потоке, не обязательно в потоке UI: подписчик,
    /// которому нужно попасть в UI-поток (например, чтобы тронуть <c>ObservableCollection</c>),
    /// отвечает за маршалинг сам.
    /// </summary>
    event EventHandler? Changed;
}
